import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
const base = 'http://localhost:3017';
const db = new DatabaseSync('.local/retail.db', { readOnly: true });
const summary = client => db.prepare('SELECT COUNT(*) AS orders, SUM(revenue) AS revenue FROM orders WHERE client_id = ?').get(client);
const res = await fetch(base + '/api/session');
const cookie = res.headers.getSetCookie().map(v => v.split(';')[0]).join('; ');
const session = await res.json();
const headers = { Cookie: cookie, Origin: base, 'x-csrf-token': session.csrf, 'Content-Type': 'application/json' };
const post = async path => { const response = await fetch(base + path, { method: 'POST', headers, body: '{}' }); const body = await response.json(); assert.equal(response.status, 200, JSON.stringify(body)); return body; };
await post('/api/sync');
const before = summary('atelier'), otherBefore = summary('coast');
const simulation = await post('/api/source/simulate');
assert.equal(simulation.order.amount, 250);
assert.deepEqual(summary('atelier'), before, 'Adding source data must not change reporting data before sync');
const imported = await post('/api/sync');
assert.equal(imported.rowsSynced, before.orders + 1);
assert.equal(summary('atelier').orders, before.orders + 1);
assert.ok(Math.abs(summary('atelier').revenue - before.revenue - 250) < 0.01);
assert.deepEqual(summary('coast'), otherBefore, 'Sync must not change the other client');
await post('/api/sync');
assert.equal(summary('atelier').orders, before.orders + 1, 'A second sync must not duplicate source rows');
const status = await (await fetch(base + '/api/sync/status', { headers: { Cookie: cookie } })).json();
assert.ok(status.lastSuccessAt);
assert.equal(Date.parse(status.nextSyncAt) - Date.parse(status.lastSuccessAt), 3600000);
const json = await (await fetch(base + '/demo-api/orders?client_id=atelier&page_size=3')).json();
assert.equal(json.data.length, 3);
assert.equal(json.meta.nextPage, 2);
console.log('PASS: paginated dummy endpoint → new $250 source order → reporting unchanged until sync → atomic import → no duplicate on retry → other client unchanged → next sync in one hour.');
db.close();
