import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
const sampleDb = new DatabaseSync('.local/retail.db', { readOnly: true });
const base = 'http://localhost:3017';
const sessionResponse = await fetch(base + '/api/session');
const cookie = sessionResponse.headers.getSetCookie().map(s => s.split(';')[0]).join('; ');
const session = await sessionResponse.json();
const headers = { Cookie: cookie, Origin: base, 'x-csrf-token': session.csrf, 'Content-Type': 'application/json' };
const blocked = await fetch(base + '/api/client', { method: 'POST', headers: { Cookie: cookie, Origin: base, 'Content-Type': 'application/json' }, body: JSON.stringify({ clientId: 'coast' }) });
assert.equal(blocked.status, 403);
const invalidClient = await fetch(base + '/api/client', { method: 'POST', headers, body: JSON.stringify({ clientId: "atelier' OR 1=1" }) });
assert.equal(invalidClient.status, 400);
const values = {};
for (const clientId of ['atelier', 'coast']) {
  const switched = await fetch(base + '/api/client', { method: 'POST', headers, body: JSON.stringify({ clientId }) });
  assert.equal(switched.status, 200);
  const tokenResponse = await fetch(base + '/api/guest-token', { method: 'POST', headers, body: '{}' });
  assert.equal(tokenResponse.status, 200);
  const { token } = await tokenResponse.json();
  const guestHeaders = { 'X-GuestToken': token, 'Content-Type': 'application/json' };
  const res = await fetch('http://localhost:8088/api/v1/dashboard/1', { headers: guestHeaders });
  assert.equal(res.status, 200);
  const chartsResponse = await fetch('http://localhost:8088/api/v1/dashboard/1/charts', { headers: guestHeaders });
  assert.equal(chartsResponse.status, 200);
  const charts = (await chartsResponse.json()).result;
  assert.equal(charts.length, 7);
  const chart = charts.find(c => c.form_data.metric?.label === 'Revenue');
  const params = chart.form_data;
  const query = { datasource: { id: Number(params.datasource.split('__')[0]), type: 'table' }, queries: [{ columns: [], metrics: [params.metric], filters: [], extras: { having: '', where: '' }, time_range: params.time_range, granularity: 'order_date', row_limit: 10000 }], form_data: { ...params, dashboardId: 1 }, result_format: 'json', result_type: 'full' };
  const dataResponse = await fetch('http://localhost:8088/api/v1/chart/data', { method: 'POST', headers: guestHeaders, body: JSON.stringify(query) });
  const body = await dataResponse.json();
  assert.equal(dataResponse.status, 200, JSON.stringify(body));
  assert.equal(body.result[0].status, 'success', JSON.stringify(body));
  values[clientId] = body.result[0].data[0].Revenue;
  const expected = sampleDb.prepare("SELECT SUM(revenue) AS total FROM orders WHERE client_id = ? AND order_date >= '2026-10-01' AND order_date < '2026-10-29'").get(clientId).total;
  assert.ok(Math.abs(values[clientId] - expected) < 0.01, `Revenue must equal only this tenant’s rows: ${values[clientId]} vs ${expected}`);
  const filteredQuery = structuredClone(query);
  filteredQuery.queries[0].filters = [{ col: 'channel', op: 'IN', val: ['Online store'] }];
  const filteredResponse = await fetch('http://localhost:8088/api/v1/chart/data', { method: 'POST', headers: guestHeaders, body: JSON.stringify(filteredQuery) });
  assert.equal(filteredResponse.status, 200);
  const filteredValue = (await filteredResponse.json()).result[0].data[0].Revenue;
  const expectedFiltered = sampleDb.prepare("SELECT SUM(revenue) AS total FROM orders WHERE client_id = ? AND channel = 'Online store' AND order_date >= '2026-10-01' AND order_date < '2026-10-29'").get(clientId).total;
  assert.ok(Math.abs(filteredValue - expectedFiltered) < 0.01, 'Channel filter must preserve tenant restriction');
  console.log(`${clientId}: 7 charts available; tenant restriction applied; October revenue $${values[clientId].toFixed(2)}`);
}
assert.notEqual(values.atelier, values.coast);
console.log('PASS: session protection, invalid-client rejection, dashboard access, and real tenant-filtered Superset queries.');
